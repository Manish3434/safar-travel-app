function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

@Injectable()
export class MockPlacesProvider implements PlacesProvider {
  async getStates(): Promise<IndianState[]> {
    return INDIAN_STATES.map((state) => {
      const count = SEED_PLACES.filter((p) => p.state_code === state.code).length;
      return {
        ...state,
        spot_count: count,
      };
    });
  }

  async getDistricts(stateCode: string): Promise<District[]> {
    const list = ALL_DISTRICTS_MAP[stateCode.toUpperCase()] || [];
    return list.map((d) => ({
      ...d,
      spot_count: SEED_PLACES.filter((p) => p.district_id === d.id).length,
    }));
  }

  async getPlacesByDistrict(districtId: string, category?: string): Promise<PlaceResult[]> {
    let places = SEED_PLACES.filter((p) => p.district_id === districtId);
    if (category && category.trim().length > 0 && category.toLowerCase() !== 'all') {
      const catLower = category.toLowerCase().trim();
      places = places.filter((p) => {
        const pCat = p.category.toLowerCase();
        if (catLower === 'beaches' || catLower === 'beach') return pCat === 'beach';
        if (catLower === 'forests' || catLower === 'forest') return pCat === 'forest';
        if (catLower === 'bird-sanctuary' || catLower === 'bird sanctuary' || catLower === 'birdsanctuary') return pCat === 'bird-sanctuary';
        if (catLower === 'wildlife' || catLower === 'wildlife sanctuary') return pCat === 'wildlife';
        if (catLower === 'heritage') return pCat === 'heritage';
        if (catLower === 'museums' || catLower === 'museum') return pCat === 'museum';
        if (catLower === 'waterfalls' || catLower === 'waterfall') return pCat === 'waterfall';
        if (catLower === 'hill-stations' || catLower === 'hill-station' || catLower === 'hill stations') return pCat === 'hill-station';
        if (catLower === 'cities' || catLower === 'city') return pCat === 'city';
        return pCat === catLower;
      });
    }
    return places.map((p) => this.maskSensitive(p));
  }

  async search(
    query: string,
    lat?: number,
    lng?: number,
    state?: string,
    district?: string,
    category?: string,
  ): Promise<PlaceResult[]> {
    const q = query.toLowerCase();
    let results = SEED_PLACES.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        (p.state_name && p.state_name.toLowerCase().includes(q)) ||
        (p.district_name && p.district_name.toLowerCase().includes(q)),
    );

    if (state) {
      results = results.filter(
        (p) =>
          p.state_code?.toLowerCase() === state.toLowerCase() ||
          p.state_name?.toLowerCase() === state.toLowerCase(),
      );
    }

    if (district) {
      results = results.filter(
        (p) =>
          p.district_id?.toLowerCase() === district.toLowerCase() ||
          p.district_name?.toLowerCase().includes(district.toLowerCase()),
      );
    }

    if (category && category.trim().length > 0 && category.toLowerCase() !== 'all') {
      const catLower = category.toLowerCase().trim();
      results = results.filter((p) => {
        const pCat = p.category.toLowerCase();
        if (catLower === 'beaches' || catLower === 'beach') return pCat === 'beach';
        if (catLower === 'forests' || catLower === 'forest') return pCat === 'forest';
        if (catLower === 'bird-sanctuary' || catLower === 'bird sanctuary' || catLower === 'birdsanctuary') return pCat === 'bird-sanctuary';
        if (catLower === 'wildlife' || catLower === 'wildlife sanctuary') return pCat === 'wildlife';
        if (catLower === 'heritage') return pCat === 'heritage';
        if (catLower === 'museums' || catLower === 'museum') return pCat === 'museum';
        if (catLower === 'waterfalls' || catLower === 'waterfall') return pCat === 'waterfall';
        if (catLower === 'hill-stations' || catLower === 'hill-station') return pCat === 'hill-station';
        if (catLower === 'cities' || catLower === 'city') return pCat === 'city';
        return pCat === catLower;
      });
    }

    if (lat !== undefined && lng !== undefined) {
      results = results.map((p) => ({
        ...p,
        distance_km: Math.round(haversineKm(lat, lng, p.location.lat, p.location.lng) * 10) / 10,
      }));
      results.sort((a, b) => (a.distance_km ?? 0) - (b.distance_km ?? 0));
    }

    // Sensitive spots: mask exact coordinates
    return results.map((p) => this.maskSensitive(p));
  }

  async getById(id: string): Promise<PlaceDetail | null> {
    const place = SEED_PLACES.find((p) => p.id === id) ?? null;
    if (!place) return null;
    return this.maskSensitive(place) as PlaceDetail;
  }

  async getNearby(lat: number, lng: number, radius: number, category?: string): Promise<PlaceResult[]> {
    let results = SEED_PLACES
      .map((p) => ({
        ...p,
        distance_km: Math.round(haversineKm(lat, lng, p.location.lat, p.location.lng) * 10) / 10,
      }))
      .filter((p) => p.distance_km <= radius);

    if (category) {
      results = results.filter((p) => p.category === category);
    }

    results.sort((a, b) => a.distance_km - b.distance_km);
    return results.map((p) => this.maskSensitive(p));
  }

  /** Sensitive spots: return approximate coordinates (±0.02°) instead of exact */
  private maskSensitive<T extends PlaceResult>(place: T): T {
    if (!place.sensitive) return place;
    return {
      ...place,
      location: {
        lat: Math.round((place.location.lat + 0.02) * 100) / 100,
        lng: Math.round((place.location.lng + 0.02) * 100) / 100,
      },
    };
  }
}
