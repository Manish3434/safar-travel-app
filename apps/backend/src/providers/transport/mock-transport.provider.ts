@Injectable()
export class MockTransportProvider implements TransportProvider {
  async getRoutes(fromStopOrCity: string, toStopOrCity: string, date?: string) {
    const from = fromStopOrCity.toLowerCase();
    const to = toStopOrCity.toLowerCase();

    const trips = SEED_ROUTES.filter(
      (r) =>
        r.from_stop.toLowerCase().includes(from) ||
        r.route_name.toLowerCase().includes(from) ||
        r.to_stop.toLowerCase().includes(to) ||
        r.route_name.toLowerCase().includes(to),
    );

    if (trips.length === 0) {
      return {
        available: false,
        trips: [],
        reason: 'No bus data available for this route. Bus timing data is being added state by state. Last updated: Oct 2026.',
      };
    }

    return { available: true, trips };
  }
}
