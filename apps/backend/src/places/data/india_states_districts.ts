// Helper to construct district items cleanly
function d(state_code: string, idSuffix: string, name: string, name_ta = '', name_hi = '', spot_count = 0, headquarters?: string): District {
  return {
    id: `${state_code.toLowerCase()}-${idSuffix.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    state_code,
    name,
    name_ta: name_ta || name,
    name_hi: name_hi || name,
    headquarters,
    spot_count,
  };
}

