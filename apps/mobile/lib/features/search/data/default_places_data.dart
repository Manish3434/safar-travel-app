/// Get fallback districts for any state code
List<District> getFallbackDistrictsForState(String stateCode) {
  final code = stateCode.toUpperCase();
  if (DEFAULT_DISTRICTS_MAP.containsKey(code)) {
    return DEFAULT_DISTRICTS_MAP[code]!;
  }
  final state = DEFAULT_STATES.firstWhere(
    (s) => s.code == code,
    orElse: () => IndianState(code: code, name: code, districtCount: 5, imageUrl: '', spotCount: 0),
  );
  return List.generate(
    state.districtCount.clamp(1, 10),
    (i) => District(
      id: '${code.toLowerCase()}-dist-${i + 1}',
      stateCode: code,
      name: '${state.name} District ${i + 1}',
      spotCount: i == 0 ? 2 : 1,
    ),
  );
}

