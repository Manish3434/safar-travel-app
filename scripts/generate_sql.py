"""
PostgreSQL Importer Script Generator.
Reads spots.csv and produces a complete, idempotent import.sql
with DDL for states, districts, spots, spot_images and initial population.
"""

import csv
import os
from config import SPOTS_CSV, IMPORT_SQL


def generate_import_sql(csv_path: str = SPOTS_CSV, sql_path: str = IMPORT_SQL) -> str:
    """Generates Postgres-ready import.sql containing schema and insert statements."""
    if not os.path.exists(csv_path):
        print(f"Warning: CSV file not found at {csv_path}")
        return ""

    rows = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(row)

    unique_states = {}
    unique_districts = {}

    for r in rows:
        sc = r.get("state_code", "").strip()
        sname = r.get("state", "").strip()
        dname = r.get("district", "").strip()
        if sc and sname:
            unique_states[sc] = sname
        if sc and dname:
            dist_id = f"{sc.lower()}-{dname.lower().replace(' ', '-')}"
            unique_districts[dist_id] = (sc, dname)

    sql_lines = [
        "-- Safar Tourist Spots Database Schema & Initial Data Import",
        "-- Auto-generated by Data Pipeline",
        "BEGIN;\n",
        "-- 1. Schema Definitions",
        "CREATE TABLE IF NOT EXISTS states (",
        "    code VARCHAR(10) PRIMARY KEY,",
        "    name VARCHAR(100) NOT NULL",
        ");\n",
        "CREATE TABLE IF NOT EXISTS districts (",
        "    id VARCHAR(100) PRIMARY KEY,",
        "    state_code VARCHAR(10) REFERENCES states(code) ON DELETE CASCADE,",
        "    name VARCHAR(100) NOT NULL",
        ");\n",
        "CREATE TABLE IF NOT EXISTS spots (",
        "    id SERIAL PRIMARY KEY,",
        "    state VARCHAR(100) NOT NULL,",
        "    state_code VARCHAR(10) REFERENCES states(code),",
        "    district VARCHAR(100) NOT NULL,",
        "    spot_name VARCHAR(255) NOT NULL,",
        "    category VARCHAR(50),",
        "    latitude NUMERIC(9,6),",
        "    longitude NUMERIC(9,6),",
        "    wikidata_id VARCHAR(50),",
        "    wikipedia_url TEXT,",
        "    created_at TIMESTAMPTZ DEFAULT NOW(),",
        "    CONSTRAINT uq_spot_name_district UNIQUE (spot_name, district)",
        ");\n",
        "CREATE TABLE IF NOT EXISTS spot_images (",
        "    id SERIAL PRIMARY KEY,",
        "    spot_id INT REFERENCES spots(id) ON DELETE CASCADE,",
        "    image_filename TEXT NOT NULL,",
        "    image_source TEXT,",
        "    license VARCHAR(100),",
        "    created_at TIMESTAMPTZ DEFAULT NOW()",
        ");\n",
        "-- Indexes for geo and district searches",
        "CREATE INDEX IF NOT EXISTS idx_spots_district ON spots(district);",
        "CREATE INDEX IF NOT EXISTS idx_spots_state ON spots(state_code);",
        "CREATE INDEX IF NOT EXISTS idx_spots_coords ON spots(latitude, longitude);\n",
        "-- 2. Seed States",
    ]

    for sc, sname in unique_states.items():
        clean_name = sname.replace("'", "''")
        sql_lines.append(f"INSERT INTO states (code, name) VALUES ('{sc}', '{clean_name}') ON CONFLICT (code) DO NOTHING;")

    sql_lines.append("\n-- 3. Seed Districts")
    for did, (sc, dname) in unique_districts.items():
        clean_dname = dname.replace("'", "''")
        sql_lines.append(f"INSERT INTO districts (id, state_code, name) VALUES ('{did}', '{sc}', '{clean_dname}') ON CONFLICT (id) DO NOTHING;")

    sql_lines.append("\n-- 4. Seed Tourist Spots & Image Records")
    for idx, r in enumerate(rows, start=1):
        sname = r.get("state", "").replace("'", "''")
        sc = r.get("state_code", "").replace("'", "''")
        dname = r.get("district", "").replace("'", "''")
        spot_name = r.get("spot_name", "").replace("'", "''")
        category = r.get("category", "attraction").replace("'", "''")
        lat = r.get("latitude") or "NULL"
        lon = r.get("longitude") or "NULL"
        wid = f"'{r['wikidata_id'].replace('\'', '\'\'')}'" if r.get("wikidata_id") else "NULL"
        wurl = f"'{r['wikipedia_url'].replace('\'', '\'\'')}'" if r.get("wikipedia_url") else "NULL"

        img_fn = r.get("image_filename", "").replace("'", "''")
        img_src = r.get("image_source", "").replace("'", "''")
        license_str = r.get("license", "").replace("'", "''")

        sql_lines.append(
            f"INSERT INTO spots (state, state_code, district, spot_name, category, latitude, longitude, wikidata_id, wikipedia_url) "
            f"VALUES ('{sname}', '{sc}', '{dname}', '{spot_name}', '{category}', {lat}, {lon}, {wid}, {wurl}) "
            f"ON CONFLICT (spot_name, district) DO UPDATE SET category = EXCLUDED.category;"
        )

        if img_fn:
            sql_lines.append(
                f"INSERT INTO spot_images (spot_id, image_filename, image_source, license) "
                f"SELECT id, '{img_fn}', '{img_src}', '{license_str}' FROM spots WHERE spot_name = '{spot_name}' AND district = '{dname}' LIMIT 1;"
            )

    sql_lines.append("\nCOMMIT;")

    sql_content = "\n".join(sql_lines) + "\n"
    with open(sql_path, "w", encoding="utf-8") as f:
        f.write(sql_content)

    print(f"Generated PostgreSQL import script: {sql_path} ({len(rows)} spots)")
    return sql_path


if __name__ == "__main__":
    generate_import_sql()
